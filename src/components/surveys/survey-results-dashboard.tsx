"use client";

import { useTransition } from "react";
import { BarChart3, Download, MessageSquareText, Star } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { canvasToBlob, drawRoundedRect, shareOrDownloadImage, wrapText } from "@/lib/canvas-share";
import { cn } from "@/lib/utils";

export type SurveyQuestionResult = {
  id: string;
  question: string;
  type: "text" | "single_choice" | "multiple_choice" | "rating";
  answeredCount: number;
  counts: { label: string; count: number }[];
  average: number | null;
  texts: string[];
};

export function SurveyResultsDashboard({ eventTitle, surveyTitle, responseCount, results }: { eventTitle: string; surveyTitle: string; responseCount: number; results: SurveyQuestionResult[] }) {
  const [pending, startTransition] = useTransition();

  function download() {
    startTransition(async () => {
      try {
        const width = 1200;
        const questionHeights = results.map((result) => result.type === "text" ? 220 : Math.max(210, 130 + result.counts.length * 42));
        const height = 330 + questionHeights.reduce((sum, value) => sum + value + 24, 0);
        const canvas = document.createElement("canvas");
        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext("2d");
        if (!ctx) throw new Error("canvas unavailable");
        const gradient = ctx.createLinearGradient(0, 0, width, 280);
        gradient.addColorStop(0, "#F0EEFF");
        gradient.addColorStop(1, "#FFF4F6");
        ctx.fillStyle = "#FAFAFC";
        ctx.fillRect(0, 0, width, height);
        ctx.fillStyle = gradient;
        ctx.fillRect(0, 0, width, 280);
        ctx.fillStyle = "#6D5DD3";
        ctx.font = "700 24px sans-serif";
        ctx.fillText("WISH Events  ·  SURVEY REPORT", 72, 70);
        ctx.fillStyle = "#252333";
        ctx.font = "800 48px sans-serif";
        wrapText(ctx, surveyTitle, 72, 132, 800, 58, 2);
        ctx.fillStyle = "#666273";
        ctx.font = "500 24px sans-serif";
        ctx.fillText(eventTitle, 72, 238);
        ctx.fillStyle = "#FFFFFF";
        drawRoundedRect(ctx, 930, 52, 190, 96, 28);
        ctx.fill();
        ctx.fillStyle = "#6D5DD3";
        ctx.font = "800 40px sans-serif";
        ctx.textAlign = "center";
        ctx.fillText(String(responseCount), 1025, 105);
        ctx.font = "600 18px sans-serif";
        ctx.fillText("responses", 1025, 133);
        ctx.textAlign = "left";

        let y = 310;
        results.forEach((result, index) => {
          const cardHeight = questionHeights[index];
          ctx.fillStyle = "#FFFFFF";
          drawRoundedRect(ctx, 56, y, 1088, cardHeight, 28);
          ctx.fill();
          ctx.fillStyle = "#ECE9FF";
          drawRoundedRect(ctx, 84, y + 28, 54, 40, 20);
          ctx.fill();
          ctx.fillStyle = "#6D5DD3";
          ctx.font = "800 20px sans-serif";
          ctx.textAlign = "center";
          ctx.fillText(`Q${index + 1}`, 111, y + 55);
          ctx.textAlign = "left";
          ctx.fillStyle = "#252333";
          ctx.font = "700 25px sans-serif";
          wrapText(ctx, result.question, 158, y + 56, 800, 32, 2);
          ctx.fillStyle = "#817C8C";
          ctx.font = "500 17px sans-serif";
          ctx.fillText(`${result.answeredCount}件の回答${result.average == null ? "" : `  ·  平均 ${result.average.toFixed(1)} / 5`}`, 84, y + 100);
          if (result.type === "text") {
            ctx.fillStyle = "#555163";
            ctx.font = "500 18px sans-serif";
            const preview = result.texts.slice(0, 2);
            preview.forEach((text, textIndex) => wrapText(ctx, `“${text}”`, 92, y + 140 + textIndex * 54, 960, 25, 2));
            if (preview.length === 0) ctx.fillText("回答はまだありません", 92, y + 150);
          } else {
            const max = Math.max(1, ...result.counts.map((item) => item.count));
            result.counts.forEach((item, itemIndex) => {
              const rowY = y + 132 + itemIndex * 42;
              ctx.fillStyle = "#555163";
              ctx.font = "600 18px sans-serif";
              ctx.fillText(item.label, 84, rowY + 16);
              ctx.fillStyle = "#EEEAFB";
              drawRoundedRect(ctx, 330, rowY, 660, 20, 10);
              ctx.fill();
              ctx.fillStyle = "#8A7BE0";
              drawRoundedRect(ctx, 330, rowY, Math.max(item.count ? 12 : 0, 660 * item.count / max), 20, 10);
              ctx.fill();
              ctx.fillStyle = "#555163";
              ctx.textAlign = "right";
              ctx.fillText(String(item.count), 1090, rowY + 17);
              ctx.textAlign = "left";
            });
          }
          y += cardHeight + 24;
        });
        ctx.fillStyle = "#817C8C";
        ctx.font = "500 16px sans-serif";
        ctx.fillText(`Generated by WISH Events · ${new Intl.DateTimeFormat("ja-JP", { dateStyle: "long" }).format(new Date())}`, 72, height - 38);
        const blob = await canvasToBlob(canvas);
        await shareOrDownloadImage(blob, `survey-${eventTitle.slice(0, 30)}.png`, `${surveyTitle} 結果`);
      } catch {
        toast.error("結果画像を作成できませんでした");
      }
    });
  }

  return <div className="space-y-5"><section className="flex flex-wrap items-end justify-between gap-3 rounded-3xl bg-gradient-to-br from-violet-500/15 via-card to-rose-400/10 p-5 sm:p-7"><div><p className="text-xs font-bold text-primary">SURVEY REPORT</p><h1 className="mt-2 text-2xl font-extrabold tracking-tight">{surveyTitle}</h1><p className="mt-1 text-sm text-muted-foreground">{eventTitle}</p></div><div className="flex items-center gap-3"><div className="rounded-2xl bg-card px-5 py-3 text-center shadow-sm"><strong className="block text-2xl text-primary">{responseCount}</strong><span className="text-[10px] text-muted-foreground">回答</span></div><Button type="button" disabled={pending} onClick={download}><Download className="h-4 w-4" />{pending ? "画像を作成中…" : "結果を画像で保存"}</Button></div></section><div className="grid gap-4 lg:grid-cols-2">{results.map((result, index) => <article key={result.id} className={cn("rounded-2xl border border-border bg-card p-4 shadow-card", result.type === "text" && "lg:col-span-2")}><div className="flex items-start gap-3"><span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl bg-primary/10 text-primary">{result.type === "text" ? <MessageSquareText className="h-4 w-4" /> : result.type === "rating" ? <Star className="h-4 w-4" /> : <BarChart3 className="h-4 w-4" />}</span><div><p className="text-[10px] font-bold text-muted-foreground">Q{index + 1} · {result.answeredCount}件</p><h2 className="mt-0.5 font-bold leading-snug">{result.question}</h2>{result.average != null && <p className="mt-2 text-xl font-extrabold text-primary">{result.average.toFixed(1)} <span className="text-xs font-medium text-muted-foreground">/ 5</span></p>}</div></div>{result.type === "text" ? <div className="mt-4 space-y-2">{result.texts.length ? result.texts.map((text, textIndex) => <p key={textIndex} className="rounded-xl bg-secondary/50 px-3 py-2.5 text-sm leading-relaxed">{text}</p>) : <p className="text-sm text-muted-foreground">回答はまだありません</p>}</div> : <div className="mt-4 space-y-3">{result.counts.map((item) => { const percent = result.answeredCount ? Math.round(item.count / result.answeredCount * 100) : 0; return <div key={item.label}><div className="mb-1 flex items-center justify-between gap-3 text-xs"><span className="truncate font-semibold">{item.label}</span><span className="shrink-0 text-muted-foreground">{item.count} · {percent}%</span></div><div className="h-2 overflow-hidden rounded-full bg-secondary"><div className="h-full rounded-full bg-primary transition-[width]" style={{ width: `${percent}%` }} /></div></div>; })}</div>}</article>)}</div></div>;
}
